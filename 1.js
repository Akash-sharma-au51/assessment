//         "month": "2024-06",
//         "totalRevenue": 150.0,
//         "averagePrice": 12.5
//     }
// ]

const salesAggregationPipeline = [
    // Stage 1: Deconstruct the items array to process each item individually.
    {
        $unwind: "$items"
    },
    // Stage 2: Group documents by store and month.
    {
        $group: {
            _id: {
                store: "$store",
                month: { $dateToString: { format: "%Y-%m", date: "$date" } }
            },
            // Calculate total revenue by multiplying quantity and price for each item and summing it up.
            totalRevenue: { $sum: { $multiply: ["$items.quantity", "$items.price"] } },
            // Calculate the average price of items sold.
            averagePrice: { $avg: "$items.price" }
        }
    },
    // Stage 3: Reshape the output documents to match the desired format.
    {
        $project: {
            _id: 0,
            store: "$_id.store",
            month: "$_id.month",
            totalRevenue: "$totalRevenue",
            averagePrice: "$averagePrice"
        }
    },
    // Stage 4: Sort the results by store and then by month.
    {
        $sort: {
            store: 1,
            month: 1
        }
    }
];





